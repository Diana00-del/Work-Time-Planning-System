CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deleted       BOOLEAN                                 NOT NULL,
    created_at    TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    created_by_id BIGINT                                  NOT NULL,
    first_name    VARCHAR(128)                            NOT NULL,
    last_name     VARCHAR(128)                            NOT NULL,
    email         VARCHAR(128)                            NOT NULL,
    phone         VARCHAR(32)                             NOT NULL,
    address       VARCHAR(512)                            NOT NULL,
    city          VARCHAR(128)                            NOT NULL,
    state         VARCHAR(128)                            NOT NULL,
    zip           VARCHAR(32)                             NOT NULL,
    country       VARCHAR(128)                            NOT NULL,
    password      VARCHAR(128)                            NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uc_users_email UNIQUE (email),
    CONSTRAINT fk_users_on_created_by FOREIGN KEY (created_by_id) REFERENCES users (id)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role    VARCHAR(255),
    CONSTRAINT fk_user_roles_on_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE session_tokens (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id BIGINT                                  NOT NULL,
    jwt     VARCHAR(4096)                           NOT NULL,
    CONSTRAINT pk_session_tokens PRIMARY KEY (id),
    CONSTRAINT fk_session_tokens_on_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE user_password_resets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    user_id    BIGINT                                  NOT NULL,
    token      VARCHAR(128)                            NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_user_password_resets PRIMARY KEY (id),
    CONSTRAINT fk_user_password_resets_on_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE locations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deleted       BOOLEAN                                 NOT NULL,
    created_at    TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    created_by_id BIGINT                                  NOT NULL,
    name          VARCHAR(255)                            NOT NULL,
    address       VARCHAR(512)                            NOT NULL,
    city          VARCHAR(128)                            NOT NULL,
    state         VARCHAR(128)                            NOT NULL,
    zip           VARCHAR(128)                            NOT NULL,
    country       VARCHAR(128)                            NOT NULL,
    phone         VARCHAR(64)                             NOT NULL,
    email         VARCHAR(128)                            NOT NULL,
    CONSTRAINT pk_locations PRIMARY KEY (id),
    CONSTRAINT fk_locations_on_created_by FOREIGN KEY (created_by_id) REFERENCES users (id)
);

CREATE TABLE time_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deleted          BOOLEAN                                 NOT NULL,
    created_at       TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    created_by_id    BIGINT                                  NOT NULL,
    user_id          BIGINT                                  NOT NULL,
    location_id      BIGINT                                  NOT NULL,
    start_time       TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    end_time         TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    description      VARCHAR(1024)                               NULL,
    status           VARCHAR(255)                            NOT NULL,
    rejection_reason VARCHAR(1024),
    CONSTRAINT pk_time_entries PRIMARY KEY (id),
    CONSTRAINT fk_time_entries_on_created_by FOREIGN KEY (created_by_id) REFERENCES users (id),
    CONSTRAINT fk_time_entries_on_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_time_entries_on_location FOREIGN KEY (location_id) REFERENCES locations (id)
);

